-- =============================================================================
-- BLOQUE 3: FUNCIÓN BASE64 → BLOB (decodifica en chunks alineados a 4)
-- Asume base64 de una sola línea (el que produce FileReader/btoa del legacy).
-- Soporta prefijo data-URI ('data:...;base64,') si viniera presente.
-- =============================================================================
CREATE OR REPLACE FUNCTION FN_BASE64_DECODE_BLOB(p_b64 IN CLOB)
RETURN BLOB
IS
  v_blob   BLOB;
  v_len    INTEGER;
  v_pos    INTEGER := 1;
  v_step   CONSTANT INTEGER := 32764;      -- múltiplo de 4 (alinea chunks base64)
  v_chunk  VARCHAR2(32767);
  v_start  INTEGER := 1;
  v_comma  INTEGER;
BEGIN
  IF p_b64 IS NULL OR DBMS_LOB.GETLENGTH(p_b64) = 0 THEN
    RETURN NULL;
  END IF;

  -- Quitar prefijo data-URI si existe: 'data:application/pdf;base64,....'
  IF DBMS_LOB.SUBSTR(p_b64, 5, 1) = 'data:' THEN
    v_comma := DBMS_LOB.INSTR(p_b64, ',', 1, 1);
    IF v_comma > 0 THEN v_start := v_comma + 1; END IF;
  END IF;

  DBMS_LOB.CREATETEMPORARY(v_blob, TRUE);
  v_len := DBMS_LOB.GETLENGTH(p_b64);
  v_pos := v_start;
  WHILE v_pos <= v_len LOOP
    v_chunk := DBMS_LOB.SUBSTR(p_b64, v_step, v_pos);
    IF v_chunk IS NOT NULL AND LENGTH(v_chunk) > 0 THEN
      DBMS_LOB.APPEND(v_blob,
        UTL_ENCODE.BASE64_DECODE(UTL_RAW.CAST_TO_RAW(v_chunk)));
    END IF;
    v_pos := v_pos + v_step;
  END LOOP;
  RETURN v_blob;
END FN_BASE64_DECODE_BLOB;
/

