BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE MED_FILE (
      -- Clave primaria
      ID            NUMBER
                    GENERATED BY DEFAULT AS IDENTITY
                    CONSTRAINT PK_MED_FILE PRIMARY KEY,

      -- Datos de negocio (mapeo directo de files legacy)
      NSS           VARCHAR2(50),            -- files.nss
      NAME          VARCHAR2(400),           -- files.name (ampliado; ver NOTA encoding)
      DATE_UPLOAD   TIMESTAMP(6),            -- files.date_upload
      FILE_TYPE     VARCHAR2(120),           -- files.type (incluye '' y hash MD5)

      -- Binario
      MIME_TYPE     VARCHAR2(200) DEFAULT 'application/pdf',
      URL_B64       CLOB,                    -- files.url: base64 FIEL del PDF
      CONTENT_BLOB  BLOB,                    -- decodificado (2º paso, nullable)
      SIZE_BYTES    NUMBER,                  -- tamaño del binario decodificado

      -- Trazabilidad de origen (no tocar tras migración)
      SOURCE_ID     NUMBER,                  -- files.id original en MariaDB
      MIGRATED_AT   TIMESTAMP(6) DEFAULT SYSTIMESTAMP,

      -- Auditoría estándar
      CREATED_AT    TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
      CREATED_BY    VARCHAR2(100) DEFAULT 'MIGRATION' NOT NULL,
      UPDATED_AT    TIMESTAMP(6),
      UPDATED_BY    VARCHAR2(100)
    )
  ]';
  DBMS_OUTPUT.PUT_LINE('[OK] Tabla MED_FILE creada.');
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE = -955 THEN DBMS_OUTPUT.PUT_LINE('[SKIP] MED_FILE ya existe.');
  ELSE RAISE; END IF;
END;
