-- BLOQUE 7: VISTAS DE RECONCILIACIÓN
-- =============================================================================
-- 7a. Resumen por tipo funcional
CREATE OR REPLACE VIEW V_MED_FILE_BY_TYPE AS
SELECT NVL(FILE_TYPE, '(vacio)') AS FILE_TYPE,
       COUNT(*) AS TOTAL_FILAS,
       COUNT(DISTINCT NSS) AS TOTAL_NSS,
       SUM(CASE WHEN CONTENT_BLOB IS NOT NULL THEN 1 ELSE 0 END) AS DECODIFICADOS,
       ROUND(SUM(NVL(SIZE_BYTES,0))/1024/1024, 2) AS MB_BINARIO
FROM MED_FILE
GROUP BY NVL(FILE_TYPE, '(vacio)')
ORDER BY TOTAL_FILAS DESC;
/

-- 7b. Huérfanos: sin binario (url vacío en origen) — se esperaban ~11
CREATE OR REPLACE VIEW V_MED_FILE_ORPHANS AS
SELECT ID, NSS, NAME, FILE_TYPE, SOURCE_ID, MIGRATED_AT
FROM   MED_FILE
WHERE  URL_B64 IS NULL OR DBMS_LOB.GETLENGTH(URL_B64) = 0;
/

-- 7c. Estado de lotes
CREATE OR REPLACE VIEW V_MED_FILE_MIG_STATUS AS
SELECT PHASE, STATUS, COUNT(*) AS LOTES,
       SUM(ROWS_EXPECTED) AS FILAS_ESPERADAS, SUM(ROWS_DONE) AS FILAS_HECHAS
FROM  MED_FILE_MIG_LOG
GROUP BY PHASE, STATUS;
/

