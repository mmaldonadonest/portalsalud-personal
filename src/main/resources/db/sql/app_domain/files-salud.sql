-- =============================================================================
-- BLOQUE 5: PROCEDIMIENTOS DE MIGRACIÓN
--
-- USO:
--   -- 1) landing fiel (metadatos + base64), dry-run primero:
--   EXEC SP_MIGRATE_FILES(p_dry_run => 'S');
--   EXEC SP_MIGRATE_FILES(p_batch_size => 50, p_dry_run => 'N');
--   -- 2) decodificar base64 -> CONTENT_BLOB (2º paso, más pesado):
--   EXEC SP_DECODE_FILE_BLOBS(p_batch_size => 50);
--
-- ⚠ LOB OVER DB LINK: seleccionar LOBs grandes vía DB Link tiene límites en
--   Oracle. Si SP_MIGRATE_FILES falla por el CLOB `url`, usar el ETL externo
--   del BLOQUE 6 (SQL*Loader), que es la vía recomendada para `files`.
-- =============================================================================
CREATE OR REPLACE PROCEDURE SP_MIGRATE_FILES (
  p_batch_size IN NUMBER DEFAULT 50,
  p_dry_run    IN CHAR   DEFAULT 'N'
)
IS
  CURSOR c_files IS
    SELECT id, nss, name, date_upload, type, url
    FROM   files@MARIADB_LINK
    WHERE  id NOT IN (SELECT SOURCE_ID FROM MED_FILE WHERE SOURCE_ID IS NOT NULL)
    ORDER BY id ASC;

  v_batch_no  NUMBER := 1;
  v_total     NUMBER := 0;
  v_cnt       NUMBER := 0;
  v_from      NUMBER;
  v_to        NUMBER;
BEGIN
  DBMS_OUTPUT.PUT_LINE('SP_MIGRATE_FILES — modo: ' ||
    CASE p_dry_run WHEN 'S' THEN 'DRY-RUN' ELSE 'REAL' END || ' lote=' || p_batch_size);

  FOR r IN c_files LOOP
    IF v_cnt = 0 THEN v_from := r.id; END IF;
    v_to := r.id;

    IF p_dry_run = 'N' THEN
      INSERT INTO MED_FILE (NSS, NAME, DATE_UPLOAD, FILE_TYPE, URL_B64,
                            SIZE_BYTES, SOURCE_ID, CREATED_BY)
      VALUES (r.nss, r.name, r.date_upload, r.type, r.url,
              NULL, r.id, 'SP_MIGRATE_FILES');
    END IF;

    v_cnt   := v_cnt + 1;
    v_total := v_total + 1;

    IF v_cnt >= p_batch_size THEN
      INSERT INTO MED_FILE_MIG_LOG (PHASE, BATCH_NO, SOURCE_ID_FROM, SOURCE_ID_TO,
             ROWS_EXPECTED, ROWS_DONE, STATUS, STARTED_AT, FINISHED_AT)
      VALUES ('LANDING', v_batch_no, v_from, v_to, v_cnt,
              CASE p_dry_run WHEN 'N' THEN v_cnt ELSE 0 END,
              CASE p_dry_run WHEN 'N' THEN 'DONE' ELSE 'DRY-RUN' END,
              SYSTIMESTAMP, SYSTIMESTAMP);
      COMMIT;
      DBMS_OUTPUT.PUT_LINE('[lote ' || v_batch_no || '] IDs ' || v_from || '→' || v_to || ' filas=' || v_cnt);
      v_batch_no := v_batch_no + 1;
      v_cnt := 0;
    END IF;
  END LOOP;

  IF v_cnt > 0 THEN
    INSERT INTO MED_FILE_MIG_LOG (PHASE, BATCH_NO, SOURCE_ID_FROM, SOURCE_ID_TO,
           ROWS_EXPECTED, ROWS_DONE, STATUS, STARTED_AT, FINISHED_AT)
    VALUES ('LANDING', v_batch_no, v_from, v_to, v_cnt,
            CASE p_dry_run WHEN 'N' THEN v_cnt ELSE 0 END,
            CASE p_dry_run WHEN 'N' THEN 'DONE' ELSE 'DRY-RUN' END,
            SYSTIMESTAMP, SYSTIMESTAMP);
    COMMIT;
  END IF;

  DBMS_OUTPUT.PUT_LINE('Total procesado: ' || v_total);
END SP_MIGRATE_FILES;
/

-- 2º paso: decodifica URL_B64 → CONTENT_BLOB y calcula SIZE_BYTES.
CREATE OR REPLACE PROCEDURE SP_DECODE_FILE_BLOBS (
  p_batch_size IN NUMBER DEFAULT 50
)
IS
  CURSOR c_pending IS
    SELECT ID, URL_B64
    FROM   MED_FILE
    WHERE  CONTENT_BLOB IS NULL
      AND  URL_B64 IS NOT NULL
      AND  DBMS_LOB.GETLENGTH(URL_B64) > 0
    FOR UPDATE OF CONTENT_BLOB, SIZE_BYTES;

  v_blob BLOB;
  v_cnt  NUMBER := 0;
BEGIN
  FOR r IN c_pending LOOP
    BEGIN
      v_blob := FN_BASE64_DECODE_BLOB(r.URL_B64);
      UPDATE MED_FILE
         SET CONTENT_BLOB = v_blob,
             SIZE_BYTES   = DBMS_LOB.GETLENGTH(v_blob),
             UPDATED_AT   = SYSTIMESTAMP,
             UPDATED_BY   = 'SP_DECODE_FILE_BLOBS'
       WHERE CURRENT OF c_pending;
    EXCEPTION WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('[ERROR decode ID ' || r.ID || '] ' || SQLERRM);
    END;

    v_cnt := v_cnt + 1;
    IF MOD(v_cnt, p_batch_size) = 0 THEN COMMIT; END IF;
  END LOOP;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('Decodificados: ' || v_cnt);
END SP_DECODE_FILE_BLOBS;
/

