-- ALCANCE
-- ───────
-- Migra la tabla `files` (adjuntos PDF del expediente) como tabla de aterrizaje
-- fiel MED_FILE, consistente con la estrategia de tags-salud.sql:
-- "landear primero sin pérdida, normalizar/optimizar después".
--
-- CONTEXTO DE LA TABLA ORIGEN (confirmado en Contexto.txt)
-- ────────────────────────────────────────────────────────
--   files
--   ├── id           int(10)   PK AUTO_INCREMENT
--   ├── nss          varchar(50)
--   ├── name         varchar(50)   -- ⚠ encoding mixto latin1/utf8 (~0.4% filas)
--   ├── date_upload  datetime
--   ├── url          longtext      -- ‼ NO es URL: es el PDF completo en base64
--   └── type         varchar(50)   -- examen_medico|nota_medica|laboratorio|
--                                   --  nota_incapacidad|''|<hash_MD5_32>
--
-- Estadística (muestra 500 filas): url base64 promedio 539 KB, p90 932 KB,
-- máx ~2 MB. 11 filas con url vacío (huérfanas). 17 GB backup total.
--
-- USO EN EL CÓDIGO (relevante para índices):
--   · Adjuntos de una consulta:  SELECT * FROM files WHERE type = <consulta_relacionada>
--   · Por NSS + type funcional:  SELECT * FROM files WHERE nss=? AND type='examen_medico'
--   · downloadPDFCons: el front toma url (base64) y la descarga como application/pdf
--
-- DECISIÓN DE DISEÑO
-- ───────────────────
-- MED_FILE guarda:
--   · URL_B64  (CLOB)  → copia FIEL del base64 de origen (cero pérdida)
--   · CONTENT_BLOB (BLOB, nullable) → binario decodificado (ahorra ~33% vs base64)
--     Se puebla en un 2º paso (SP_DECODE_FILE_BLOBS) tras validar el landing.
-- Una vez validado CONTENT_BLOB se puede vaciar URL_B64 para recuperar espacio.
-- Prereq de ejecución: DB Link a MariaDB o export (ver BLOQUE 6). Igual que tags.
-- =============================================================================

SET SERVEROUTPUT ON;

