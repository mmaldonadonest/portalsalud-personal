-- BLOQUE 9: NOTAS
-- =============================================================================
-- [NOTA-1] ENCODING DE `name`
--   ~0.4% de files.name tiene tildes dobles-codificadas (latin1/utf8). Corregir
--   al EXPORTAR (--default-character-set=utf8mb4). Post-fix opcional en Oracle:
--   UPDATE MED_FILE SET NAME = CONVERT(NAME,'UTF8','WE8ISO8859P1') WHERE ...;
--   (validar caso por caso; no aplicar a ciegas.)
--
-- [NOTA-2] BLOB vs base64
--   URL_B64 es el landing fiel. CONTENT_BLOB ahorra ~33%. Tras validar el
--   decode, para recuperar espacio: UPDATE MED_FILE SET URL_B64 = NULL
--   WHERE CONTENT_BLOB IS NOT NULL;  (¡solo tras respaldo y validación!)
--
-- [NOTA-3] files.type = hash MD5 (~9.4%)
--   Origen a confirmar en el PHP. En el detalle de consulta, los adjuntos se
--   buscan por  type = consulta_relacionada  → esos hashes son la relación
--   consulta↔archivo. Conservar FILE_TYPE tal cual (no normalizar aún).
--
-- [NOTA-4] Integración con Java (U04 adjuntos)
