SET PAGESIZE 200
SET LINESIZE 200
COLUMN ORIGEN FORMAT A28
COLUMN PREDIO FORMAT A20

SELECT 'ATENCIONES' ORIGEN, UPPER(TRIM(PREDIO)) PREDIO, FUENTE, COUNT(*) RENGLONES
  FROM SERV_MED_V_ATENCION
 WHERE UPPER(TRIM(PREDIO)) IN ('KILOTON', 'MALTA', 'SIGLO', 'TULTITLAN')
 GROUP BY UPPER(TRIM(PREDIO)), FUENTE
UNION ALL
SELECT 'EXAMENES', UPPER(TRIM(PREDIO)), FUENTE, COUNT(*)
  FROM SERV_MED_V_EXAMEN
 WHERE UPPER(TRIM(PREDIO)) IN ('KILOTON', 'MALTA', 'SIGLO', 'TULTITLAN')
 GROUP BY UPPER(TRIM(PREDIO)), FUENTE
UNION ALL
SELECT 'INCAPACIDADES', UPPER(TRIM(PREDIO)), FUENTE, COUNT(*)
  FROM SERV_MED_V_INCAPACIDAD
 WHERE UPPER(TRIM(PREDIO)) IN ('KILOTON', 'MALTA', 'SIGLO', 'TULTITLAN')
 GROUP BY UPPER(TRIM(PREDIO)), FUENTE
UNION ALL
SELECT 'ACCIDENTES', UPPER(TRIM(PREDIO)), FUENTE, COUNT(*)
  FROM SERV_MED_V_ACCIDENTE
 WHERE UPPER(TRIM(PREDIO)) IN ('KILOTON', 'MALTA', 'SIGLO', 'TULTITLAN')
 GROUP BY UPPER(TRIM(PREDIO)), FUENTE
UNION ALL
SELECT 'ANTIDOPING', UPPER(TRIM(PREDIO)), FUENTE, COUNT(*)
  FROM SERV_MED_V_ANTIDOPING
 WHERE UPPER(TRIM(PREDIO)) IN ('KILOTON', 'MALTA', 'SIGLO', 'TULTITLAN')
 GROUP BY UPPER(TRIM(PREDIO)), FUENTE
UNION ALL
SELECT 'MATERNIDAD', UPPER(TRIM(PREDIO)), FUENTE, COUNT(*)
  FROM SERV_MED_V_MATERNIDAD
 WHERE UPPER(TRIM(PREDIO)) IN ('KILOTON', 'MALTA', 'SIGLO', 'TULTITLAN')
 GROUP BY UPPER(TRIM(PREDIO)), FUENTE
UNION ALL
SELECT 'CONSUMIBLES MEDICAMENTO', UPPER(TRIM(PREDIO)), 'EXCEL', COUNT(*)
  FROM SERV_MED_XLS_MEDICAMENTO
 WHERE UPPER(TRIM(PREDIO)) IN ('KILOTON', 'MALTA', 'SIGLO', 'TULTITLAN')
 GROUP BY UPPER(TRIM(PREDIO))
UNION ALL
SELECT 'CONSUMIBLES MATERIAL FIJO', UPPER(TRIM(PREDIO)), 'EXCEL', COUNT(*)
  FROM SERV_MED_XLS_MATERIAL_FIJO
 WHERE UPPER(TRIM(PREDIO)) IN ('KILOTON', 'MALTA', 'SIGLO', 'TULTITLAN')
 GROUP BY UPPER(TRIM(PREDIO))
 ORDER BY 1, 2;
