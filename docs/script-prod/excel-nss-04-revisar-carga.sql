-- CARGA DE EXCEL POR NSS -- REVISAR LO QUE SE CARGO. SOLO LECTURA.
-- Base: BIOMETRICO de produccion. Lo corre el usuario despues de nss-cargar.
-- =============================================================================
SET LINESIZE 220
SET PAGESIZE 500
COLUMN layout   FORMAT A18
COLUMN tabla    FORMAT A26
COLUMN archivo  FORMAT A60
COLUMN predio   FORMAT A16

-- 1) Lotes: un renglon por archivo cargado
SELECT ID lote, LAYOUT layout, ESTADO, PREDIO predio, FILAS_LEIDAS leidas, FILAS_VALIDAS validas,
       FILAS_DUPLICADAS duplicadas, FILAS_ERROR errores,
       TO_CHAR(PERIODO_DESDE, 'DD/MM/YYYY') desde, TO_CHAR(PERIODO_HASTA, 'DD/MM/YYYY') hasta,
       SUBSTR(ARCHIVO, INSTR(ARCHIVO, '\', -1) + 1) archivo
  FROM SERV_MED_XLS_LOTE
 ORDER BY ID;

-- 2) Renglones por tabla: validos y duplicados (duplicado = ya estaba en el portal)
SELECT 'SERV_MED_XLS_ATENCION' tabla, ESTADO_REGISTRO, COUNT(*) renglones FROM SERV_MED_XLS_ATENCION GROUP BY ESTADO_REGISTRO
UNION ALL SELECT 'SERV_MED_XLS_EXAMEN_ING', ESTADO_REGISTRO, COUNT(*) FROM SERV_MED_XLS_EXAMEN_ING GROUP BY ESTADO_REGISTRO
UNION ALL SELECT 'SERV_MED_XLS_EXAMEN_PER', ESTADO_REGISTRO, COUNT(*) FROM SERV_MED_XLS_EXAMEN_PER GROUP BY ESTADO_REGISTRO
UNION ALL SELECT 'SERV_MED_XLS_INCAPACIDAD', ESTADO_REGISTRO, COUNT(*) FROM SERV_MED_XLS_INCAPACIDAD GROUP BY ESTADO_REGISTRO
UNION ALL SELECT 'SERV_MED_XLS_ACCIDENTE', ESTADO_REGISTRO, COUNT(*) FROM SERV_MED_XLS_ACCIDENTE GROUP BY ESTADO_REGISTRO
 ORDER BY 1, 2;

-- 3) Atenciones por predio y mes (lo que deberian mostrar las graficas)
SELECT PREDIO predio, TO_CHAR(FECHA, 'YYYY-MM') mes, COUNT(*) atenciones, COUNT(DISTINCT NSS) personas
  FROM SERV_MED_XLS_ATENCION
 WHERE ESTADO_REGISTRO = 'VALIDO'
 GROUP BY PREDIO, TO_CHAR(FECHA, 'YYYY-MM')
 ORDER BY 1, 2;

-- 4) Resumen por layout: renglones, personas, rango de fechas
SELECT 'ATENCIONES' layout, COUNT(*) renglones, COUNT(DISTINCT NSS) personas, MIN(FECHA) desde, MAX(FECHA) hasta FROM SERV_MED_XLS_ATENCION WHERE ESTADO_REGISTRO = 'VALIDO'
UNION ALL SELECT 'EXAMEN INGRESO', COUNT(*), COUNT(DISTINCT NSS), MIN(FECHA), MAX(FECHA) FROM SERV_MED_XLS_EXAMEN_ING WHERE ESTADO_REGISTRO = 'VALIDO'
UNION ALL SELECT 'EXAMEN PERIODICO', COUNT(*), COUNT(DISTINCT NSS), MIN(FECHA), MAX(FECHA) FROM SERV_MED_XLS_EXAMEN_PER WHERE ESTADO_REGISTRO = 'VALIDO'
UNION ALL SELECT 'INCAPACIDADES', COUNT(*), COUNT(DISTINCT NSS), MIN(FECHA), MAX(FECHA) FROM SERV_MED_XLS_INCAPACIDAD WHERE ESTADO_REGISTRO = 'VALIDO'
UNION ALL SELECT 'ACCIDENTES', COUNT(*), COUNT(DISTINCT NSS), MIN(FECHA), MAX(FECHA) FROM SERV_MED_XLS_ACCIDENTE WHERE ESTADO_REGISTRO = 'VALIDO';

-- 5) Datos del biometrico que quedaron vacios (por layout de empleados)
SELECT 'ATENCIONES' layout, COUNT(*) total,
       SUM(CASE WHEN CUENTA IS NULL THEN 1 ELSE 0 END) sin_cuenta,
       SUM(CASE WHEN PUESTO IS NULL THEN 1 ELSE 0 END) sin_puesto,
       SUM(CASE WHEN GENERO IS NULL THEN 1 ELSE 0 END) sin_genero,
       SUM(CASE WHEN EDAD IS NULL THEN 1 ELSE 0 END) sin_edad
  FROM SERV_MED_XLS_ATENCION
UNION ALL SELECT 'INCAPACIDADES', COUNT(*), SUM(CASE WHEN CUENTA IS NULL THEN 1 ELSE 0 END),
       SUM(CASE WHEN PUESTO IS NULL THEN 1 ELSE 0 END), SUM(CASE WHEN GENERO IS NULL THEN 1 ELSE 0 END),
       SUM(CASE WHEN EDAD IS NULL THEN 1 ELSE 0 END) FROM SERV_MED_XLS_INCAPACIDAD
UNION ALL SELECT 'ACCIDENTES', COUNT(*), SUM(CASE WHEN CUENTA IS NULL THEN 1 ELSE 0 END),
       SUM(CASE WHEN PUESTO IS NULL THEN 1 ELSE 0 END), SUM(CASE WHEN GENERO IS NULL THEN 1 ELSE 0 END),
       SUM(CASE WHEN EDAD IS NULL THEN 1 ELSE 0 END) FROM SERV_MED_XLS_ACCIDENTE;

-- 6) Muestra: 10 atenciones cualquiera, para ver como quedaron los datos
SELECT * FROM (
  SELECT LOTE_ID, ORIGEN_FILA, NSS, NOMBRE, PREDIO, AREA, TO_CHAR(FECHA, 'DD/MM/YYYY') fecha, RAMO, CAUSA,
         GENERO, EDAD, CUENTA, PUESTO, ESTADO_REGISTRO
    FROM SERV_MED_XLS_ATENCION ORDER BY ID
) WHERE ROWNUM <= 10;

-- 7) Si hubo duplicados contra el portal: cuales y con que registro coincidieron
SELECT 'ATENCIONES' layout, NSS, TO_CHAR(FECHA, 'DD/MM/YYYY') fecha, DUPLICADO_DE FROM SERV_MED_XLS_ATENCION WHERE ESTADO_REGISTRO = 'DUPLICADO'
UNION ALL SELECT 'INCAPACIDADES', NSS, TO_CHAR(FECHA, 'DD/MM/YYYY'), DUPLICADO_DE FROM SERV_MED_XLS_INCAPACIDAD WHERE ESTADO_REGISTRO = 'DUPLICADO'
UNION ALL SELECT 'ACCIDENTES', NSS, TO_CHAR(FECHA, 'DD/MM/YYYY'), DUPLICADO_DE FROM SERV_MED_XLS_ACCIDENTE WHERE ESTADO_REGISTRO = 'DUPLICADO'
UNION ALL SELECT 'EXAMEN INGRESO', NSS, TO_CHAR(FECHA, 'DD/MM/YYYY'), DUPLICADO_DE FROM SERV_MED_XLS_EXAMEN_ING WHERE ESTADO_REGISTRO = 'DUPLICADO'
UNION ALL SELECT 'EXAMEN PERIODICO', NSS, TO_CHAR(FECHA, 'DD/MM/YYYY'), DUPLICADO_DE FROM SERV_MED_XLS_EXAMEN_PER WHERE ESTADO_REGISTRO = 'DUPLICADO';
