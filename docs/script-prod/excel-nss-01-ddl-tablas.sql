-- ======================================================================
-- INDICES: por NSS (expediente y comparacion contra el portal), por fecha+predio
-- (graficas), por lote (reversa) y renglon unico por lote (la misma celda no entra dos veces).
-- ======================================================================
DECLARE
  PROCEDURE ix(p_sql VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
  END;
BEGIN
  ix('CREATE UNIQUE INDEX SERV_MED_UX_XLS_ATN_FILA ON SERV_MED_XLS_ATENCION (LOTE_ID, ORIGEN_FILA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_ATN_NSS ON SERV_MED_XLS_ATENCION (NSS, FECHA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_ATN_FECHA ON SERV_MED_XLS_ATENCION (FECHA, PREDIO)');

  ix('CREATE UNIQUE INDEX SERV_MED_UX_XLS_EXI_FILA ON SERV_MED_XLS_EXAMEN_ING (LOTE_ID, ORIGEN_FILA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_EXI_NSS ON SERV_MED_XLS_EXAMEN_ING (NSS, FECHA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_EXI_FECHA ON SERV_MED_XLS_EXAMEN_ING (FECHA, PREDIO)');

  ix('CREATE UNIQUE INDEX SERV_MED_UX_XLS_EXP_FILA ON SERV_MED_XLS_EXAMEN_PER (LOTE_ID, ORIGEN_FILA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_EXP_NSS ON SERV_MED_XLS_EXAMEN_PER (NSS, FECHA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_EXP_FECHA ON SERV_MED_XLS_EXAMEN_PER (FECHA, PREDIO)');

  ix('CREATE UNIQUE INDEX SERV_MED_UX_XLS_INC_FILA ON SERV_MED_XLS_INCAPACIDAD (LOTE_ID, ORIGEN_FILA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_INC_NSS ON SERV_MED_XLS_INCAPACIDAD (NSS, FECHA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_INC_FECHA ON SERV_MED_XLS_INCAPACIDAD (FECHA, PREDIO)');
  ix('CREATE INDEX SERV_MED_IX_XLS_INC_FOLIO ON SERV_MED_XLS_INCAPACIDAD (FOLIO)');

  ix('CREATE UNIQUE INDEX SERV_MED_UX_XLS_ACC_FILA ON SERV_MED_XLS_ACCIDENTE (LOTE_ID, ORIGEN_FILA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_ACC_NSS ON SERV_MED_XLS_ACCIDENTE (NSS, FECHA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_ACC_FECHA ON SERV_MED_XLS_ACCIDENTE (FECHA, PREDIO)');

  ix('CREATE INDEX SERV_MED_IX_XLS_LOTE_PRED ON SERV_MED_XLS_LOTE (LAYOUT, PREDIO, PERIODO_DESDE)');
END;
/

-- ----------------------------------------------------------------------
-- VERIFICACION (solo lectura). Esperado: 6 tablas VALID, 23 indices (17 explicitos + 6 de PK),
-- 6 llaves primarias, 5 foraneas.
-- ----------------------------------------------------------------------
SELECT table_name, status FROM user_tables WHERE table_name LIKE 'SERV_MED_XLS%' ORDER BY 1;
SELECT table_name, COUNT(*) indices FROM user_indexes WHERE table_name LIKE 'SERV_MED_XLS%' GROUP BY table_name ORDER BY 1;
SELECT table_name, constraint_type, COUNT(*) FROM user_constraints
 WHERE table_name LIKE 'SERV_MED_XLS%' AND constraint_type IN ('P','R')
 GROUP BY table_name, constraint_type ORDER BY 1, 2;
