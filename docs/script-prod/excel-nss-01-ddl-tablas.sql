-- =============================================================================
-- CARGA DE EXCEL POR NSS -- DDL de las tablas nuevas (paso 3 del plan)
--
-- BASE: la del PORTAL = BIOMETRICO de produccion (misma base que leen los WS de ORDS).
-- LO CORRE: el usuario. Layouts con visto bueno el 10-oct (1, 2, 3, 5 y 6). Las columnas pueden
--           ajustarse hasta la carga de prueba (paso 6): mientras las tablas esten vacias, se
--           recrean con excel-nss-99-reversa-tablas.sql y este script corregido.
--
-- QUE HACE:  crea 6 tablas nuevas (1 de lotes + 1 por layout), sus indices y llaves foraneas
--            ENTRE ELLAS.
-- QUE NO HACE: ningun ALTER, DROP, TRUNCATE, GRANT ni UPDATE sobre nada que ya exista.
--            La carga vieja por nombre (SERV_MED_BITACORA_*) queda intacta y congelada.
--
-- Columnas = encabezados de docs/09102026/ (1 ATENCIONES, 2 EXAMEN NUEVO INGRESO,
-- 3 EXAMEN PERIODICO, 5 INCAPACIDADES, 6 ACCIDENTES). Los montos y dias se guardan TAL COMO SE CAPTURAN: no se
-- recalculan (decision del 8-oct: "lo que suben es lo que manda").
--
-- Columnas comunes a las 4 tablas de evento:
--   NSS, PREDIO, AREA         obligatorios en el layout (regla 3 del LEEME)
--   NOMBRE, GENERO, EDAD,     se copian del biometrico AL CARGAR y se congelan: si la persona
--   CUENTA, PUESTO            cambia de cuenta despues, la historia no se mueve
--   ESTADO_REGISTRO           VALIDO o DUPLICADO ("si ya esta en el portal, manda el portal")
--   DUPLICADO_DE              referencia del registro del portal con el que coincidio
--   ORIGEN_FILA               renglon del Excel, para rastrear cada cifra hasta la celda
--
-- Idempotente: si un objeto ya existe lo salta (-955 / -1408). Nombres <= 30 caracteres.
-- =============================================================================
SET SERVEROUTPUT ON
SET LINESIZE 200

-- ----------------------------------------------------------------------
-- PRE-CHECK (solo lectura)
-- ----------------------------------------------------------------------
DECLARE
  v_n NUMBER;
BEGIN
  DBMS_OUTPUT.PUT_LINE('Usuario: ' || USER || '  PDB: ' || SYS_CONTEXT('USERENV','CON_NAME'));
  SELECT COUNT(*) INTO v_n FROM user_objects
   WHERE object_name IN ('SERV_MED_XLS_LOTE','SERV_MED_XLS_ATENCION','SERV_MED_XLS_EXAMEN_ING',
                         'SERV_MED_XLS_EXAMEN_PER','SERV_MED_XLS_INCAPACIDAD','SERV_MED_XLS_ACCIDENTE');
  DBMS_OUTPUT.PUT_LINE(CASE WHEN v_n = 0 THEN 'Las 6 tablas no existen: se van a crear.'
                            ELSE 'ATENCION: ya existen ' || v_n || ' de las 6; se saltan, no se modifican.' END);
END;
/

-- ======================================================================
-- 1 de 6: SERV_MED_XLS_LOTE  -- un renglon por archivo cargado
-- Es la unidad de reversa: borrar un lote borra exactamente lo que entro con el.
-- ======================================================================
BEGIN EXECUTE IMMEDIATE q'[
  CREATE TABLE SERV_MED_XLS_LOTE (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT SERV_MED_PK_XLS_LOTE PRIMARY KEY,
    LAYOUT           VARCHAR2(30)  NOT NULL,   -- ATENCIONES | EXAMEN_INGRESO | EXAMEN_PERIODICO | INCAPACIDADES | ACCIDENTES
    ARCHIVO          VARCHAR2(400) NOT NULL,
    CHECKSUM_SHA256  VARCHAR2(64),             -- detecta que se volvio a subir el mismo archivo
    PREDIO           VARCHAR2(120),            -- predio del archivo (reemplazo por predio y periodo)
    PERIODO_DESDE    DATE,
    PERIODO_HASTA    DATE,
    FILAS_LEIDAS     NUMBER DEFAULT 0,
    FILAS_VALIDAS    NUMBER DEFAULT 0,
    FILAS_DUPLICADAS NUMBER DEFAULT 0,         -- ya estaban en el portal: no cuentan
    FILAS_ERROR      NUMBER DEFAULT 0,         -- no entraron; detalle en REPORTE
    ESTADO           VARCHAR2(20) DEFAULT 'EN_CURSO' NOT NULL, -- EN_CURSO | OK | CON_ERRORES | REVERTIDO
    REPORTE          CLOB,                     -- renglon y motivo de cada error, para el predio
    CREATED_AT       TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY       VARCHAR2(100) DEFAULT 'CARGA_EXCEL_NSS' NOT NULL
  )]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955) THEN RAISE; END IF; END;
/
COMMENT ON TABLE SERV_MED_XLS_LOTE IS 'Carga de Excel por NSS: un renglon por archivo. Unidad de reversa.';

