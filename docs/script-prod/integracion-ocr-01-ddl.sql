-- =============================================================================
-- Integracion OCR -> Portal Salud: solicitudes de examen medico inicial y envios del webhook.
-- PRODUCCION: ejecutar en BIOMETRICO@PDBPRD (base del portal), NO en ORDS. Copia exacta de
-- src/main/resources/db/sql/app_domain/integracion-ocr.sql (QA). Idempotente. Quien lo ejecuta: el
-- usuario/DBA en SQL Developer; el agente no ejecuta nada contra esta base.
-- REVERSA (al pie, comentada): DROP de las 2 tablas en orden inverso.
-- Contrato: docs/integracion-ocr-examen-inicial.md
--
-- SERV_MED_EXAMEN_SOLICITUD: una fila por solicitud que manda OCR (candidato que debe pasar
--   examen inicial). Hace de FICHA del candidato mientras no existe en el biometrico: el portal
--   la muestra al buscar el NSS y abre el examen inicial. Estatus PENDIENTE -> EN_CAPTURA ->
--   FINALIZADO | CANCELADO (por OCR o por caducidad).
-- SERV_MED_INTEGRACION_ENVIO: cada intento de avisar a OCR (webhook) con su resultado, para
--   reintentos automaticos y reenvio manual desde /admin/integracion-ocr.
-- =============================================================================
SET SERVEROUTPUT ON;
SET DEFINE OFF;

BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE SERV_MED_EXAMEN_SOLICITUD (
      ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY
                         CONSTRAINT SERV_MED_PK_EXAMEN_SOLIC PRIMARY KEY,
      ORIGEN             VARCHAR2(20)  DEFAULT 'OCR' NOT NULL,
      REFERENCIA         VARCHAR2(120) NOT NULL,              -- referenciaOcr (unica por origen)
      NSS                VARCHAR2(50)  NOT NULL,
      CURP               VARCHAR2(20)  NOT NULL,
      RFC                VARCHAR2(20),
      NOMBRE             VARCHAR2(120) NOT NULL,
      APELLIDO_PATERNO   VARCHAR2(120) NOT NULL,
      APELLIDO_MATERNO   VARCHAR2(120) NOT NULL,
      FECHA_NACIMIENTO   DATE,
      SEXO               CHAR(1),                             -- M | F
      ESTADO_CIVIL       VARCHAR2(60),
      ESCOLARIDAD        VARCHAR2(120),
      PROFESION_OFICIO   VARCHAR2(160),
      DOMICILIO          VARCHAR2(400),
      TELEFONO           VARCHAR2(40),
      EMPRESA            VARCHAR2(200),
      CUENTA             VARCHAR2(200) NOT NULL,
      AGENCIA            VARCHAR2(120),
      PUESTO_SOLICITADO  VARCHAR2(200) NOT NULL,
      FECHA_CITA         DATE,
      CALLBACK_URL       VARCHAR2(600),
      ESTATUS            VARCHAR2(20)  DEFAULT 'PENDIENTE' NOT NULL,
      CADUCA             DATE          NOT NULL,
      MOTIVO_CANCEL      VARCHAR2(400),
      CANCELADO_AT       TIMESTAMP(6),
      DICTAMEN           VARCHAR2(30),                        -- apto | no_apto | apto_condicionado | apto_restringido
      FECHA_EXAMEN       TIMESTAMP(6),
      HISTORICO_ID       NUMBER,                              -- SERV_MED_EXAMEN_HISTORICO.ID del examen finalizado
      NOTIFICADO_AT      TIMESTAMP(6),                        -- webhook aceptado por OCR (2xx)
      CREATED_AT         TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
      CREATED_IP         VARCHAR2(60),
      UPDATED_AT         TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT SERV_MED_UK_EXAMEN_SOLIC_REF UNIQUE (ORIGEN, REFERENCIA),
      CONSTRAINT SERV_MED_CK_EXAMEN_SOLIC_EST CHECK (ESTATUS IN ('PENDIENTE','EN_CAPTURA','FINALIZADO','CANCELADO')),
      CONSTRAINT SERV_MED_CK_EXAMEN_SOLIC_SEX CHECK (SEXO IS NULL OR SEXO IN ('M','F'))
    )
  ]';
  DBMS_OUTPUT.PUT_LINE('SERV_MED_EXAMEN_SOLICITUD creada');
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; ELSE DBMS_OUTPUT.PUT_LINE('SERV_MED_EXAMEN_SOLICITUD ya existia'); END IF; END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX SERV_MED_IX_EXAMEN_SOLIC_NSS ON SERV_MED_EXAMEN_SOLICITUD (NSS, ESTATUS)';
  DBMS_OUTPUT.PUT_LINE('SERV_MED_IX_EXAMEN_SOLIC_NSS creado');
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; ELSE DBMS_OUTPUT.PUT_LINE('SERV_MED_IX_EXAMEN_SOLIC_NSS ya existia'); END IF; END;
/

BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE SERV_MED_INTEGRACION_ENVIO (
      ID             NUMBER GENERATED BY DEFAULT AS IDENTITY
                     CONSTRAINT SERV_MED_PK_INTEG_ENVIO PRIMARY KEY,
      SOLICITUD_ID   NUMBER        NOT NULL,
      EVENTO         VARCHAR2(60)  NOT NULL,                  -- EXAMEN_INICIAL_FINALIZADO
      URL            VARCHAR2(600) NOT NULL,
      CUERPO         CLOB,                                    -- JSON enviado (sin la firma)
      INTENTO        NUMBER(3)     DEFAULT 1 NOT NULL,
      PROGRAMADO_AT  TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
      ENVIADO_AT     TIMESTAMP(6),
      HTTP_CODE      NUMBER(3),
      RESPUESTA      VARCHAR2(2000),
      ESTATUS        VARCHAR2(20)  DEFAULT 'PENDIENTE' NOT NULL, -- PENDIENTE | OK | FALLO | AGOTADO
      CREATED_AT     TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
      CREATED_BY     VARCHAR2(100),
      CONSTRAINT SERV_MED_FK_INTEG_ENVIO_SOL FOREIGN KEY (SOLICITUD_ID) REFERENCES SERV_MED_EXAMEN_SOLICITUD (ID),
      CONSTRAINT SERV_MED_CK_INTEG_ENVIO_EST CHECK (ESTATUS IN ('PENDIENTE','OK','FALLO','AGOTADO'))
    )
  ]';
  DBMS_OUTPUT.PUT_LINE('SERV_MED_INTEGRACION_ENVIO creada');
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; ELSE DBMS_OUTPUT.PUT_LINE('SERV_MED_INTEGRACION_ENVIO ya existia'); END IF; END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX SERV_MED_IX_INTEG_ENVIO_PEND ON SERV_MED_INTEGRACION_ENVIO (ESTATUS, PROGRAMADO_AT)';
  DBMS_OUTPUT.PUT_LINE('SERV_MED_IX_INTEG_ENVIO_PEND creado');
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; ELSE DBMS_OUTPUT.PUT_LINE('SERV_MED_IX_INTEG_ENVIO_PEND ya existia'); END IF; END;
/

-- Menu de administracion (grupo /admin, rol ADMIN): seguimiento de solicitudes y reenvio del webhook.
-- El panel /admin ya se protege por rol en SecurityConfiguration; no necesita SERV_MED_MENU.

SELECT object_type, object_name, status FROM user_objects
 WHERE object_name IN ('SERV_MED_EXAMEN_SOLICITUD','SERV_MED_IX_EXAMEN_SOLIC_NSS','SERV_MED_INTEGRACION_ENVIO','SERV_MED_IX_INTEG_ENVIO_PEND')
 ORDER BY 1, 2;

