--
-- BASE: la del PORTAL = BIOMETRICO de produccion. LO CORRE: el usuario.
-- Layout de docs/09102026/corregidos/8 MATERNIDAD CORREGIDO.xlsx (12-oct-2026).
--
-- QUE HACE:  crea 1 tabla nueva, sus indices y su llave foranea a SERV_MED_XLS_LOTE.
-- QUE NO HACE: ningun ALTER, DROP, TRUNCATE, GRANT ni UPDATE sobre nada que ya exista.
--
-- Decisiones del 12-oct-2026:
--   - ES SEGUIMIENTO Y SE GUARDA EL HISTORIAL EN ESTA MISMA TABLA (sin bitacora aparte): cada
--     archivo agrega un renglon por caso por MES REPORTADO. FECHA = fecha de corte / mes reportado
--     (sustituye las columnas mensuales B:N del Excel viejo, LEEME!A19). Reenviar el mismo mes de
--     un predio reemplaza solo ese mes; los meses anteriores quedan como historial.
--   - El EMBARAZO se identifica por NSS + FUM; si falta la FUM, NSS + FECHA PROBABLE DE PARTO.
--     CLAVE_EMBARAZO lo guarda ya armado para agrupar el historial y sacar el estado actual (la
--     "ultima actualizacion" = el renglon de FECHA mas reciente de cada clave).
--   - El FOLIO DE INCAPACIDAD NO identifica el embarazo (no existe en los primeros meses y puede
--     haber varios); se guarda para cruzar con el layout 5 INCAPACIDADES (ramo MAT).
--   - "Manda el portal": si el portal tiene un chequeo (SERV_MED_MATERNIDAD_SEGUIMIENTO) de la
--     misma persona en el mismo mes del corte, el renglon del Excel de ese mes queda DUPLICADO.
--
-- Idempotente: si un objeto ya existe lo salta (-955 / -1408). Nombres <= 30 caracteres.
-- =============================================================================
SET SERVEROUTPUT ON
SET LINESIZE 200

-- ----------------------------------------------------------------------
-- PRE-CHECK (solo lectura)
-- ----------------------------------------------------------------------
DECLARE
  v_n NUMBER;
BEGIN
  DBMS_OUTPUT.PUT_LINE('Usuario: ' || USER || '  PDB: ' || SYS_CONTEXT('USERENV','CON_NAME'));
  SELECT COUNT(*) INTO v_n FROM user_tables WHERE table_name = 'SERV_MED_XLS_LOTE';
  IF v_n = 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'No existe SERV_MED_XLS_LOTE: correr antes excel-nss-01-ddl-tablas.sql');
  END IF;
  SELECT COUNT(*) INTO v_n FROM user_objects WHERE object_name = 'SERV_MED_XLS_MATERNIDAD';
  DBMS_OUTPUT.PUT_LINE(CASE WHEN v_n = 0 THEN 'La tabla no existe: se va a crear.'
                            ELSE 'ATENCION: la tabla ya existe; se salta, no se modifica.' END);
END;
/

-- ======================================================================
-- SERV_MED_XLS_MATERNIDAD  -- layout 8 MATERNIDAD, un renglon por caso por mes reportado
-- Empleadas: nombre, genero, edad, cuenta y puesto se copian del biometrico al cargar.
-- ======================================================================
BEGIN EXECUTE IMMEDIATE q'[
  CREATE TABLE SERV_MED_XLS_MATERNIDAD (
    ID                         NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT SERV_MED_PK_XLS_MATERNIDAD PRIMARY KEY,
    LOTE_ID                    NUMBER        NOT NULL,
    ORIGEN_FILA                NUMBER        NOT NULL,
    NSS                        VARCHAR2(13)  NOT NULL,
    PREDIO                     VARCHAR2(120) NOT NULL,
    AREA                       VARCHAR2(120) NOT NULL,
    FECHA                      DATE          NOT NULL,   -- fecha de corte / mes reportado
    CLAVE_EMBARAZO             VARCHAR2(40)  NOT NULL,   -- NSS|FUM:aaaa-mm-dd  o  NSS|FPP:aaaa-mm-dd
    STATUS_LABORAL             VARCHAR2(30),             -- LABORANDO EMBARAZADA | INCAPACIDAD | LACTANCIA | ...
    FUM                        DATE,
    FECHA_PROB_PARTO           DATE,
    FECHA_PROB_INCAP_PRENATAL  DATE,
    FECHA_PROB_REINICIO        DATE,                     -- FECHA PROBABLE REINICIO DE LABORES
    FECHA_REAL_REINICIO        DATE,                     -- FECHA REAL DE REINICIO DE LABORES
    FECHA_INICIO_INCAP         DATE,
    FECHA_TERMINO_INCAP        DATE,
    FOLIO_INCAPACIDAD          VARCHAR2(20),             -- liga con el layout 5 (ramo MAT), no identifica el embarazo
    FECHA_INICIO_LACTANCIA     DATE,
    FECHA_TERMINO_LACTANCIA    DATE,
    FECHA_REANUDA_HORARIO      DATE,                     -- REANUDACION DE ACTIVIDADES EN HORARIO NORMAL
    CORREO_AVISO_EMBARAZO      DATE,
    CORREO_AVISO_LACTANCIA     DATE,
    CORREO_AVISO_TERM_LACT     DATE,                     -- CORREO DE AVISO TERMINO DE LACTANCIA
    NOMBRE                     VARCHAR2(300),
    GENERO                     VARCHAR2(10),
    EDAD                       NUMBER(3),
    CUENTA                     VARCHAR2(160),
    PUESTO                     VARCHAR2(160),
    ESTADO_REGISTRO            VARCHAR2(12) DEFAULT 'VALIDO' NOT NULL
                               CONSTRAINT SERV_MED_CK_XLS_MAT_EST CHECK (ESTADO_REGISTRO IN ('VALIDO','DUPLICADO')),
    DUPLICADO_DE               VARCHAR2(60),
    CREATED_AT                 TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT SERV_MED_FK_XLS_MAT_LOTE FOREIGN KEY (LOTE_ID) REFERENCES SERV_MED_XLS_LOTE (ID)
  )]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955) THEN RAISE; END IF; END;
/
COMMENT ON TABLE SERV_MED_XLS_MATERNIDAD IS 'Carga de Excel por NSS: layout 8 MATERNIDAD, seguimiento con historial (un renglon por caso por mes reportado; embarazo = CLAVE_EMBARAZO). 12-oct-2026.';

-- ======================================================================
-- INDICES: por embarazo (historial y estado actual), por NSS (expediente y portal), por
-- fecha+predio (graficas y reemplazo) y renglon unico por lote.
-- ======================================================================
DECLARE
  PROCEDURE ix(p_sql VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
  END;
BEGIN
  ix('CREATE UNIQUE INDEX SERV_MED_UX_XLS_MAT_FILA ON SERV_MED_XLS_MATERNIDAD (LOTE_ID, ORIGEN_FILA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_MAT_EMB ON SERV_MED_XLS_MATERNIDAD (CLAVE_EMBARAZO, FECHA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_MAT_NSS ON SERV_MED_XLS_MATERNIDAD (NSS, FECHA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_MAT_FECHA ON SERV_MED_XLS_MATERNIDAD (FECHA, PREDIO)');
END;
/

