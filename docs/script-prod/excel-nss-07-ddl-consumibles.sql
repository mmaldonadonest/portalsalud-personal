-- CARGA DE EXCEL -- DDL de 2 layouts mas: 9 CONSUMIBLES MEDICAMENTOS y 9 CONSUMIBLES MATERIAL FIJO
--
-- BASE: la del PORTAL = BIOMETRICO de produccion. LO CORRE: el usuario.
-- Layouts de docs/09102026/corregidos/ (12-oct-2026).
--
-- QUE HACE:  crea 2 tablas nuevas, sus indices y su llave foranea a SERV_MED_XLS_LOTE (que ya
--            existe, creada por excel-nss-01-ddl-tablas.sql).
-- QUE NO HACE: ningun ALTER, DROP, TRUNCATE, GRANT ni UPDATE sobre nada que ya exista.
--
-- Diferencias con las tablas por persona:
--   - Sin NSS ni datos del biometrico: son inventario del consultorio, no eventos de una persona.
--   - Sin comparacion contra el portal: el "consumibles" del portal es el inventario de kits de
--     antidoping (SERV_MED_ANTIDOPING_INVENTARIO), otra cosa. ESTADO_REGISTRO siempre VALIDO; se
--     deja para que todas las tablas SERV_MED_XLS_* se lean igual.
--   - Lo capturado manda: totales, acumulados y existencias se guardan tal como vienen. "DIAS PARA
--     CADUCAR" y "ORDEN FIFO" NO se guardan: son formulas que dependen del dia en que se abre.
--
-- MEDICAMENTOS: FECHA = dia 1 del MES y ANO capturados (columna AÑO agregada el 12-oct-2026: en el
-- Excel original el mes es un encabezado de texto y el ano solo esta en la celda A2).
--
-- Idempotente: si un objeto ya existe lo salta (-955 / -1408). Nombres <= 30 caracteres.
-- =============================================================================
SET SERVEROUTPUT ON
SET LINESIZE 200

-- ----------------------------------------------------------------------
-- PRE-CHECK (solo lectura)
-- ----------------------------------------------------------------------
DECLARE
  v_n NUMBER;
BEGIN
  DBMS_OUTPUT.PUT_LINE('Usuario: ' || USER || '  PDB: ' || SYS_CONTEXT('USERENV','CON_NAME'));
  SELECT COUNT(*) INTO v_n FROM user_tables WHERE table_name = 'SERV_MED_XLS_LOTE';
  IF v_n = 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'No existe SERV_MED_XLS_LOTE: correr antes excel-nss-01-ddl-tablas.sql');
  END IF;
  SELECT COUNT(*) INTO v_n FROM user_objects
   WHERE object_name IN ('SERV_MED_XLS_MEDICAMENTO','SERV_MED_XLS_MATERIAL_FIJO');
  DBMS_OUTPUT.PUT_LINE(CASE WHEN v_n = 0 THEN 'Las 2 tablas no existen: se van a crear.'
                            ELSE 'ATENCION: ya existen ' || v_n || ' de las 2; se saltan, no se modifican.' END);
END;
/

-- ======================================================================
-- 1 de 2: SERV_MED_XLS_MEDICAMENTO  -- layout 9 CONSUMIBLES MEDICAMENTOS
-- Un renglon = un lote de un medicamento, en un predio, en un mes.
-- ======================================================================
BEGIN EXECUTE IMMEDIATE q'[
  CREATE TABLE SERV_MED_XLS_MEDICAMENTO (
    ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT SERV_MED_PK_XLS_MEDICAMENTO PRIMARY KEY,
    LOTE_ID              NUMBER        NOT NULL,
    ORIGEN_FILA          NUMBER        NOT NULL,
    PREDIO               VARCHAR2(120) NOT NULL,
    FECHA                DATE          NOT NULL,   -- dia 1 del MES / AÑO capturados
    MES                  VARCHAR2(12)  NOT NULL,   -- ENERO .. DICIEMBRE
    ANIO                 NUMBER(4)     NOT NULL,
    CATEGORIA            VARCHAR2(40),             -- VIA ORAL | INYECTABLE | ... | URGENCIA
    DESCRIPCION          VARCHAR2(200) NOT NULL,   -- el medicamento
    LOTE_MEDICAMENTO     VARCHAR2(60),             -- columna LOTE del layout (no confundir con LOTE_ID)
    FECHA_INGRESO        DATE,                     -- FECHA DE INGRESO DEL LOTE
    FECHA_CADUCIDAD      DATE,
    CANTIDAD_MES_ANT     NUMBER(12,2),             -- CANTIDAD MES ANTERIOR
    RECIBIDO_MES         NUMBER(12,2),             -- RECIBIDO EN EL MES
    CONSUMO_S1           NUMBER(12,2),
    CONSUMO_S2           NUMBER(12,2),
    CONSUMO_S3           NUMBER(12,2),
    CONSUMO_S4           NUMBER(12,2),
    CONSUMO_S5           NUMBER(12,2),
    TOTAL_LOTE           NUMBER(12,2),             -- TOTAL x LOTE
    CONSUMO_ACUMULADO    NUMBER(12,2),
    RESTANTE_LOTE        NUMBER(12,2),             -- RESTANTE PARA USO x LOTE
    EXISTENCIA_PROX_MES  NUMBER(12,2),             -- TOTAL EN EXISTENCIA PARA PROXIMO MES
    ESTADO_REGISTRO      VARCHAR2(12) DEFAULT 'VALIDO' NOT NULL
                         CONSTRAINT SERV_MED_CK_XLS_MED_EST CHECK (ESTADO_REGISTRO IN ('VALIDO','DUPLICADO')),
    DUPLICADO_DE         VARCHAR2(60),
    CREATED_AT           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT SERV_MED_FK_XLS_MED_LOTE FOREIGN KEY (LOTE_ID) REFERENCES SERV_MED_XLS_LOTE (ID)
  )]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955) THEN RAISE; END IF; END;
/
COMMENT ON TABLE SERV_MED_XLS_MEDICAMENTO IS 'Carga de Excel: layout 9 CONSUMIBLES MEDICAMENTOS, un renglon por lote x predio x mes (12-oct-2026).';

-- ======================================================================
-- 2 de 2: SERV_MED_XLS_MATERIAL_FIJO  -- layout 9 CONSUMIBLES MATERIAL FIJO
-- Un renglon = una recepcion de equipo en un predio. FECHA = FECHA DE RECEPCION.
-- ======================================================================
BEGIN EXECUTE IMMEDIATE q'[
  CREATE TABLE SERV_MED_XLS_MATERIAL_FIJO (
    ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT SERV_MED_PK_XLS_MAT_FIJO PRIMARY KEY,
    LOTE_ID              NUMBER        NOT NULL,
    ORIGEN_FILA          NUMBER        NOT NULL,
    PREDIO               VARCHAR2(120) NOT NULL,
    EQUIPO               VARCHAR2(60)  NOT NULL,   -- ALCOHOLIMETRO | BAUMANOMETRO | ...
    TIPO_MATERIAL        VARCHAR2(200),            -- texto libre (sin catalogo por ahora)
    FECHA                DATE          NOT NULL,   -- FECHA DE RECEPCION
    MOTIVO               VARCHAR2(20),             -- INICIAL | CAMBIO | DAÑO | AUMENTO
    CANTIDAD_SURTIDA     NUMBER(12,2),
    FECHA_BAJA           DATE,
    CANTIDAD_TOTAL       NUMBER(12,2),             -- CANTIDAD TOTAL SURTIDA
    ESTADO_REGISTRO      VARCHAR2(12) DEFAULT 'VALIDO' NOT NULL
                         CONSTRAINT SERV_MED_CK_XLS_MFI_EST CHECK (ESTADO_REGISTRO IN ('VALIDO','DUPLICADO')),
    DUPLICADO_DE         VARCHAR2(60),
    CREATED_AT           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT SERV_MED_FK_XLS_MFI_LOTE FOREIGN KEY (LOTE_ID) REFERENCES SERV_MED_XLS_LOTE (ID)
  )]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955) THEN RAISE; END IF; END;
/
COMMENT ON TABLE SERV_MED_XLS_MATERIAL_FIJO IS 'Carga de Excel: layout 9 CONSUMIBLES MATERIAL FIJO, un renglon por recepcion de equipo (12-oct-2026).';

-- ======================================================================
-- INDICES: por fecha+predio (graficas y reemplazo por predio y mes), por medicamento (ranking)
-- y renglon unico por lote (la misma celda no entra dos veces).
-- ======================================================================
DECLARE
  PROCEDURE ix(p_sql VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
  END;
BEGIN
  ix('CREATE UNIQUE INDEX SERV_MED_UX_XLS_MED_FILA ON SERV_MED_XLS_MEDICAMENTO (LOTE_ID, ORIGEN_FILA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_MED_FECHA ON SERV_MED_XLS_MEDICAMENTO (FECHA, PREDIO)');
  ix('CREATE INDEX SERV_MED_IX_XLS_MED_DESC ON SERV_MED_XLS_MEDICAMENTO (DESCRIPCION, FECHA)');

  ix('CREATE UNIQUE INDEX SERV_MED_UX_XLS_MFI_FILA ON SERV_MED_XLS_MATERIAL_FIJO (LOTE_ID, ORIGEN_FILA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_MFI_FECHA ON SERV_MED_XLS_MATERIAL_FIJO (FECHA, PREDIO)');
END;
/

-- ----------------------------------------------------------------------
-- VERIFICACION (solo lectura). Esperado: 2 tablas; MEDICAMENTO 4 indices y MATERIAL_FIJO 3
-- (explicitos + PK); 1 llave primaria y 1 foranea cada una.
-- ----------------------------------------------------------------------
SELECT table_name, status FROM user_tables
 WHERE table_name IN ('SERV_MED_XLS_MEDICAMENTO','SERV_MED_XLS_MATERIAL_FIJO') ORDER BY 1;
SELECT table_name, COUNT(*) indices FROM user_indexes
 WHERE table_name IN ('SERV_MED_XLS_MEDICAMENTO','SERV_MED_XLS_MATERIAL_FIJO') GROUP BY table_name ORDER BY 1;
SELECT table_name, constraint_type, COUNT(*) FROM user_constraints
 WHERE table_name IN ('SERV_MED_XLS_MEDICAMENTO','SERV_MED_XLS_MATERIAL_FIJO') AND constraint_type IN ('P','R')
 GROUP BY table_name, constraint_type ORDER BY 1, 2;

