-- LO CORRE: el usuario. Layouts de docs/09102026/corregidos/ (12-oct-2026).
--
-- QUE HACE:  crea 2 tablas nuevas, sus indices y su llave foranea a SERV_MED_XLS_LOTE (que ya
--            existe, creada por excel-nss-01-ddl-tablas.sql).
-- QUE NO HACE: ningun ALTER, DROP, TRUNCATE, GRANT ni UPDATE sobre nada que ya exista.
--
-- Mismas reglas que las 5 tablas del 10-oct: lo capturado manda (no se recalcula); NOMBRE,
-- GENERO, EDAD, CUENTA y PUESTO se copian del biometrico al cargar y se congelan; ESTADO_REGISTRO
-- VALIDO o DUPLICADO ("si ya esta en el portal, manda el portal"); ORIGEN_FILA para rastrear la celda.
--
-- Decisiones del 12-oct-2026:
--   - Pos incapacidad: SIN las columnas de dias / inicio / ultimo dia / inicio de labores que
--     sugeria el comentario de la plantilla.
--   - Antidoping: SOLO EMPLEADOS (el NSS debe existir en el biometrico). El de candidatos ya se
--     captura en el examen inicial del portal.
--
-- Idempotente: si un objeto ya existe lo salta (-955 / -1408). Nombres <= 30 caracteres.
-- =============================================================================
SET SERVEROUTPUT ON
SET LINESIZE 200

-- ----------------------------------------------------------------------
-- PRE-CHECK (solo lectura)
-- ----------------------------------------------------------------------
DECLARE
  v_n NUMBER;
BEGIN
  DBMS_OUTPUT.PUT_LINE('Usuario: ' || USER || '  PDB: ' || SYS_CONTEXT('USERENV','CON_NAME'));
  SELECT COUNT(*) INTO v_n FROM user_tables WHERE table_name = 'SERV_MED_XLS_LOTE';
  IF v_n = 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'No existe SERV_MED_XLS_LOTE: correr antes excel-nss-01-ddl-tablas.sql');
  END IF;
  SELECT COUNT(*) INTO v_n FROM user_objects
   WHERE object_name IN ('SERV_MED_XLS_EXAMEN_POS','SERV_MED_XLS_ANTIDOPING');
  DBMS_OUTPUT.PUT_LINE(CASE WHEN v_n = 0 THEN 'Las 2 tablas no existen: se van a crear.'
                            ELSE 'ATENCION: ya existen ' || v_n || ' de las 2; se saltan, no se modifican.' END);
END;
/

-- ======================================================================
-- 1 de 2: SERV_MED_XLS_EXAMEN_POS  -- layout 4 EXAMEN POS INCAPACIDAD
-- Empleados: nombre, genero, edad, cuenta y puesto se copian del biometrico al cargar.
-- CAUSA = ramo de la incapacidad que origino el examen (EG | MAT | RT 1 | RT 2 | INTERNA).
-- ======================================================================
BEGIN EXECUTE IMMEDIATE q'[
  CREATE TABLE SERV_MED_XLS_EXAMEN_POS (
    ID                     NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT SERV_MED_PK_XLS_EXAMEN_POS PRIMARY KEY,
    LOTE_ID                NUMBER        NOT NULL,
    ORIGEN_FILA            NUMBER        NOT NULL,
    NSS                    VARCHAR2(13)  NOT NULL,
    FECHA                  DATE          NOT NULL,   -- FECHA EXAMEN
    CAUSA                  VARCHAR2(20),             -- EG | MAT | RT 1 | RT 2 | INTERNA
    FOLIO_INCAPACIDAD      VARCHAR2(20),
    PREDIO                 VARCHAR2(120) NOT NULL,
    AREA                   VARCHAR2(120) NOT NULL,
    DICTAMEN               VARCHAR2(30),             -- STATUS: APTO | APTO_CONDICIONADO | APTO_RESTRINGIDO | NO_APTO
    DIAGNOSTICO            VARCHAR2(1000),
    RESULTADOS_PENDIENTES  VARCHAR2(500),
    NOMBRE                 VARCHAR2(300),
    GENERO                 VARCHAR2(10),
    EDAD                   NUMBER(3),
    CUENTA                 VARCHAR2(160),
    PUESTO                 VARCHAR2(160),
    ESTADO_REGISTRO        VARCHAR2(12) DEFAULT 'VALIDO' NOT NULL
                           CONSTRAINT SERV_MED_CK_XLS_EXO_EST CHECK (ESTADO_REGISTRO IN ('VALIDO','DUPLICADO')),
    DUPLICADO_DE           VARCHAR2(60),
    CREATED_AT             TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT SERV_MED_FK_XLS_EXO_LOTE FOREIGN KEY (LOTE_ID) REFERENCES SERV_MED_XLS_LOTE (ID)
  )]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955) THEN RAISE; END IF; END;
/
COMMENT ON TABLE SERV_MED_XLS_EXAMEN_POS IS 'Carga de Excel por NSS: layout 4 EXAMEN POS INCAPACIDAD (12-oct-2026).';

-- ======================================================================
-- 2 de 2: SERV_MED_XLS_ANTIDOPING  -- layout 7 ANTIDOPING (solo empleados)
-- Una fila = una prueba. DOPING = sustancia (solo antidoping); ALCOHOLEMIA = % (solo alcoholemia).
-- ======================================================================
BEGIN EXECUTE IMMEDIATE q'[
  CREATE TABLE SERV_MED_XLS_ANTIDOPING (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT SERV_MED_PK_XLS_ANTIDOPING PRIMARY KEY,
    LOTE_ID            NUMBER        NOT NULL,
    ORIGEN_FILA        NUMBER        NOT NULL,
    NSS                VARCHAR2(13)  NOT NULL,
    PREDIO             VARCHAR2(120) NOT NULL,
    AREA               VARCHAR2(120) NOT NULL,
    FECHA              DATE          NOT NULL,
    TIPO_PRUEBA        VARCHAR2(20)  NOT NULL,   -- ANTIDOPING | ALCOHOLEMIA
    RESULTADO          VARCHAR2(20)  NOT NULL,   -- NEGATIVO | POSITIVO
    SUSTANCIA          VARCHAR2(20),             -- DOPING: AMF | BARB | BENZO | COC | LSD | MET | OPI | PVC | THC | SOLVENTE | OTRO
    ALCOHOLEMIA        NUMBER(8,4),              -- ALCOHOLEMIA %
    CONCLUSION         VARCHAR2(40),             -- N/A | CAPA | NO INTERESADO / BAJA | NO CONTRATADO | RECAIDA
    STATUS             VARCHAR2(40),             -- LABORANDO | BAJA / NO CONTRATADO
    OBSERVACIONES      VARCHAR2(1000),
    NOMBRE             VARCHAR2(300),
    GENERO             VARCHAR2(10),
    EDAD               NUMBER(3),
    CUENTA             VARCHAR2(160),
    PUESTO             VARCHAR2(160),
    ESTADO_REGISTRO    VARCHAR2(12) DEFAULT 'VALIDO' NOT NULL
                       CONSTRAINT SERV_MED_CK_XLS_ADP_EST CHECK (ESTADO_REGISTRO IN ('VALIDO','DUPLICADO')),
    DUPLICADO_DE       VARCHAR2(60),
    CREATED_AT         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT SERV_MED_FK_XLS_ADP_LOTE FOREIGN KEY (LOTE_ID) REFERENCES SERV_MED_XLS_LOTE (ID)
  )]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955) THEN RAISE; END IF; END;
/
COMMENT ON TABLE SERV_MED_XLS_ANTIDOPING IS 'Carga de Excel por NSS: layout 7 ANTIDOPING, solo empleados (12-oct-2026).';

-- ======================================================================
-- INDICES: por NSS (expediente y comparacion contra el portal), por fecha+predio (graficas)
-- y renglon unico por lote (la misma celda no entra dos veces).
-- ======================================================================
DECLARE
  PROCEDURE ix(p_sql VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
  END;
BEGIN
  ix('CREATE UNIQUE INDEX SERV_MED_UX_XLS_EXO_FILA ON SERV_MED_XLS_EXAMEN_POS (LOTE_ID, ORIGEN_FILA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_EXO_NSS ON SERV_MED_XLS_EXAMEN_POS (NSS, FECHA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_EXO_FECHA ON SERV_MED_XLS_EXAMEN_POS (FECHA, PREDIO)');

  ix('CREATE UNIQUE INDEX SERV_MED_UX_XLS_ADP_FILA ON SERV_MED_XLS_ANTIDOPING (LOTE_ID, ORIGEN_FILA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_ADP_NSS ON SERV_MED_XLS_ANTIDOPING (NSS, FECHA)');
  ix('CREATE INDEX SERV_MED_IX_XLS_ADP_FECHA ON SERV_MED_XLS_ANTIDOPING (FECHA, PREDIO)');
END;
/

-- ----------------------------------------------------------------------
-- VERIFICACION (solo lectura). Esperado: 2 tablas, 4 indices cada una (3 explicitos + PK),
-- 1 llave primaria y 1 foranea cada una.
-- ----------------------------------------------------------------------
SELECT table_name, status FROM user_tables
 WHERE table_name IN ('SERV_MED_XLS_EXAMEN_POS','SERV_MED_XLS_ANTIDOPING') ORDER BY 1;
SELECT table_name, COUNT(*) indices FROM user_indexes
 WHERE table_name IN ('SERV_MED_XLS_EXAMEN_POS','SERV_MED_XLS_ANTIDOPING') GROUP BY table_name ORDER BY 1;
SELECT table_name, constraint_type, COUNT(*) FROM user_constraints
 WHERE table_name IN ('SERV_MED_XLS_EXAMEN_POS','SERV_MED_XLS_ANTIDOPING') AND constraint_type IN ('P','R')
 GROUP BY table_name, constraint_type ORDER BY 1, 2;

