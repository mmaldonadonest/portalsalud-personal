-- -------------------------------------------------------------------------------------
-- 4. Historico de examenes finalizados (foto completa por examen, desde los dos modulos)
-- -------------------------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE SERV_MED_EXAMEN_HISTORICO (
      ID             NUMBER GENERATED BY DEFAULT AS IDENTITY
                     CONSTRAINT SERV_MED_PK_EXAMEN_HIST PRIMARY KEY,
      NSS            VARCHAR2(50)  NOT NULL,
      ORIGEN         VARCHAR2(20)  NOT NULL,            -- INICIAL (modulo inicial) | GENERAL (modulo Examen medico)
      TIPO_EXAMEN    VARCHAR2(5),                       -- codigo del legacy: 1 Admision, 2 Periodico, 3 Cambio de rol,
                                                        -- 4 Post incapacidad, 5 Especial; NULL si no se capturo
      DICTAMEN       VARCHAR2(30),                      -- apto | no_apto | apto_condicionado | apto_restringido
      FECHA_EXAMEN   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
      USUARIO        VARCHAR2(100),
      DATOS          CLOB,                              -- examen completo aplanado {SECCION.CAMPO: valor}
      CREATED_AT     TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT SERV_MED_CK_EXAMEN_HIST_ORI CHECK (ORIGEN IN ('INICIAL','GENERAL'))
    )
  ]';
  DBMS_OUTPUT.PUT_LINE('SERV_MED_EXAMEN_HISTORICO creada');
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; ELSE DBMS_OUTPUT.PUT_LINE('SERV_MED_EXAMEN_HISTORICO ya existia'); END IF; END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX SERV_MED_IX_EXAMEN_HIST_NSS ON SERV_MED_EXAMEN_HISTORICO (NSS, FECHA_EXAMEN)';
  DBMS_OUTPUT.PUT_LINE('SERV_MED_IX_EXAMEN_HIST_NSS creado');
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; ELSE DBMS_OUTPUT.PUT_LINE('SERV_MED_IX_EXAMEN_HIST_NSS ya existia'); END IF; END;
/

