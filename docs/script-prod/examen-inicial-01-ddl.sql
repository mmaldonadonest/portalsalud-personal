                       'SERV_MED_NOTIFICACION', 'SERV_MED_PK_NOTIFICACION', 'SERV_MED_IX_NOTIF_PEND',
                       'SERV_MED_EXAMEN_HISTORICO', 'SERV_MED_PK_EXAMEN_HIST', 'SERV_MED_IX_EXAMEN_HIST_NSS');
SELECT ID, CODE, TITLE FROM SERV_MED_MENU WHERE CODE = 'EXAMEN_INICIAL';

-- -------------------------------------------------------------------------------------
-- 1. Borrador del examen inicial
-- -------------------------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE SERV_MED_EXAMEN_BORRADOR (
      ID             NUMBER GENERATED BY DEFAULT AS IDENTITY
                     CONSTRAINT SERV_MED_PK_EXAMEN_BORRADOR PRIMARY KEY,
      NSS            VARCHAR2(50)  NOT NULL,
      TIPO_EXAMEN    VARCHAR2(20)  DEFAULT 'INICIAL'  NOT NULL,   -- INICIAL (unico por ahora)
      ESTATUS        VARCHAR2(20)  DEFAULT 'BORRADOR' NOT NULL,   -- BORRADOR | FINALIZADO
      HOJA_ACTUAL    NUMBER(2)     DEFAULT 1 NOT NULL,            -- donde se quedo el medico
      DATOS          CLOB,                                        -- JSON {clave: valor}
      CREATED_AT     TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
      CREATED_BY     VARCHAR2(100),
      UPDATED_AT     TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_BY     VARCHAR2(100),
      FINALIZADO_AT  TIMESTAMP(6),
      FINALIZADO_BY  VARCHAR2(100),
      CONSTRAINT SERV_MED_CK_EXAMEN_BORR_EST CHECK (ESTATUS IN ('BORRADOR','FINALIZADO'))
    )
  ]';
  DBMS_OUTPUT.PUT_LINE('SERV_MED_EXAMEN_BORRADOR creada');
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; ELSE DBMS_OUTPUT.PUT_LINE('SERV_MED_EXAMEN_BORRADOR ya existia'); END IF; END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX SERV_MED_IX_EXAMEN_BORR_NSS ON SERV_MED_EXAMEN_BORRADOR (NSS, ESTATUS)';
  DBMS_OUTPUT.PUT_LINE('SERV_MED_IX_EXAMEN_BORR_NSS creado');
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; ELSE DBMS_OUTPUT.PUT_LINE('SERV_MED_IX_EXAMEN_BORR_NSS ya existia'); END IF; END;
/

-- -------------------------------------------------------------------------------------
-- 2. Menu EXAMEN_INICIAL, asignado a los roles que ya ven EXAMEN_MEDICO
--    (fragments/nss-modules.html resuelve la pantalla por CODE; el ID es el IDENTITY)
-- -------------------------------------------------------------------------------------
DECLARE
  v_n NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_n FROM SERV_MED_MENU WHERE CODE = 'EXAMEN_INICIAL';
  IF v_n = 0 THEN
    INSERT INTO SERV_MED_MENU (CODE, TITLE, ICON, ORDER_NO, ACTIVE)
    VALUES ('EXAMEN_INICIAL', 'Examen Médico Inicial', 'ri-file-add-line',
            (SELECT NVL(MAX(ORDER_NO), 0) + 1 FROM SERV_MED_MENU WHERE CODE = 'EXAMEN_MEDICO'), 'Y');
    DBMS_OUTPUT.PUT_LINE('Menu EXAMEN_INICIAL insertado');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Menu EXAMEN_INICIAL ya existia');
  END IF;

  INSERT INTO SERV_MED_MENU_ROLE (MENU_ID, ROLE_ID)
  SELECT n.ID, mr.ROLE_ID
    FROM SERV_MED_MENU n, SERV_MED_MENU m
    JOIN SERV_MED_MENU_ROLE mr ON mr.MENU_ID = m.ID
   WHERE n.CODE = 'EXAMEN_INICIAL' AND m.CODE = 'EXAMEN_MEDICO'
     AND NOT EXISTS (SELECT 1 FROM SERV_MED_MENU_ROLE x WHERE x.MENU_ID = n.ID AND x.ROLE_ID = mr.ROLE_ID);
  DBMS_OUTPUT.PUT_LINE('Roles asignados a EXAMEN_INICIAL: ' || SQL%ROWCOUNT);
  COMMIT;
END;
/

-- -------------------------------------------------------------------------------------
-- 3. Notificaciones (campanita)
-- -------------------------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE SERV_MED_NOTIFICACION (
      ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY
                         CONSTRAINT SERV_MED_PK_NOTIFICACION PRIMARY KEY,
      TIPO               VARCHAR2(40)  NOT NULL,          -- EXAMEN_INICIAL_SOLICITUD, ...
      TITULO             VARCHAR2(200) NOT NULL,
      MENSAJE            VARCHAR2(1000),
      NSS                VARCHAR2(50),
      ENLACE             VARCHAR2(400),                   -- ruta relativa al portal (nss?nss=...&abrir=examen-inicial)
      DESTINO_MENU_CODE  VARCHAR2(120),                   -- la ven los roles con ese menu (SERV_MED_MENU.CODE)
      DESTINO_USUARIO    VARCHAR2(100),                   -- o un usuario concreto
      ORIGEN             VARCHAR2(60),                    -- OCR, PORTAL, ...
      REFERENCIA         VARCHAR2(120),                   -- id externo (p.ej. referenciaOcr)
      CREATED_AT         TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
      CREATED_BY         VARCHAR2(100),
      LEIDA_AT           TIMESTAMP(6),
      LEIDA_POR          VARCHAR2(100)
    )
  ]';
  DBMS_OUTPUT.PUT_LINE('SERV_MED_NOTIFICACION creada');
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; ELSE DBMS_OUTPUT.PUT_LINE('SERV_MED_NOTIFICACION ya existia'); END IF; END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX SERV_MED_IX_NOTIF_PEND ON SERV_MED_NOTIFICACION (LEIDA_AT, CREATED_AT)';
