SELECT object_type, object_name, status
  FROM user_objects
 WHERE object_name IN ('SERV_MED_EXAMEN_BORRADOR', 'SERV_MED_IX_EXAMEN_BORR_NSS', 'SERV_MED_NOTIFICACION', 'SERV_MED_IX_NOTIF_PEND',
                       'SERV_MED_EXAMEN_HISTORICO', 'SERV_MED_IX_EXAMEN_HIST_NSS')
 ORDER BY 1, 2;
SELECT m.CODE, m.TITLE, m.ACTIVE, COUNT(mr.ROLE_ID) AS roles
  FROM SERV_MED_MENU m LEFT JOIN SERV_MED_MENU_ROLE mr ON mr.MENU_ID = m.ID
 WHERE m.CODE IN ('EXAMEN_MEDICO', 'EXAMEN_INICIAL')
 GROUP BY m.CODE, m.TITLE, m.ACTIVE;

