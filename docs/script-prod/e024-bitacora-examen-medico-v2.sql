PROMPT === 2) Clones PR_SERVICIO_MED_EXAMEN1_V2 y PR_SERVICIO_MED_EXAMEN2_V2 (desde el codigo vivo) ===
DECLARE
  PROCEDURE clonar(p_original IN VARCHAR2) IS
    v_src    CLOB;
    v_nuevo  CLOB;
    v_clon   VARCHAR2(60) := p_original || '_V2';
    v_estado VARCHAR2(20);
  BEGIN
    DBMS_LOB.CREATETEMPORARY(v_src, TRUE);
    FOR l IN (SELECT TEXT FROM USER_SOURCE WHERE NAME = p_original AND TYPE = 'PROCEDURE' ORDER BY LINE) LOOP
      DBMS_LOB.APPEND(v_src, l.TEXT);
    END LOOP;
    -- a) nombre, solo en el encabezado (primera aparicion: "PROCEDURE PR_...")
    v_nuevo := REGEXP_REPLACE(v_src, '(PROCEDURE\s+)' || p_original || '(\W)', '\1' || v_clon || '\2', 1, 1, 'i');
    -- b) el WHEN OTHERS final: anota el error y luego sigue igual (KRESPUESTA := 1)
    v_nuevo := REGEXP_REPLACE(v_nuevo,
      'WHEN\s+OTHERS\s+THEN\s+KRESPUESTA\s*:=\s*1\s*;\s*END\s+' || p_original || '\s*;',
      'WHEN OTHERS THEN PR_SERV_MED_LOG_PROC(''' || v_clon || ''', KNNS, SQLCODE, SQLERRM, DBMS_UTILITY.FORMAT_ERROR_BACKTRACE); '
        || 'KRESPUESTA := 1; END ' || v_clon || ';', 1, 1, 'i');
    IF INSTR(v_nuevo, 'PR_SERV_MED_LOG_PROC') = 0 OR INSTR(UPPER(v_nuevo), 'PROCEDURE ' || v_clon) = 0 THEN
      RAISE_APPLICATION_ERROR(-20010, p_original || ': el codigo vivo no tiene la forma esperada; no se creo ' || v_clon || '.');
    END IF;
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || v_nuevo;
    SELECT STATUS INTO v_estado FROM USER_OBJECTS WHERE OBJECT_NAME = v_clon AND OBJECT_TYPE = 'PROCEDURE';
    DBMS_OUTPUT.PUT_LINE(v_clon || ' creado: ' || v_estado);
    IF v_estado <> 'VALID' THEN
      RAISE_APPLICATION_ERROR(-20011, v_clon || ' quedo INVALIDO: revisar USER_ERRORS antes de seguir.');
    END IF;
  END;
BEGIN
  clonar('PR_SERVICIO_MED_EXAMEN1');
  clonar('PR_SERVICIO_MED_EXAMEN2');
END;
