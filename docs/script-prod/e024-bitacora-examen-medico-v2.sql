PROMPT === 3) Handler POST Servcio/Medico_v2 (copia del vivo, llamando a los _V2) ===
DECLARE
  v_src   CLOB;
  v_nuevo CLOB;
BEGIN
  SELECT h.SOURCE INTO v_src
    FROM USER_ORDS_HANDLERS h
    JOIN USER_ORDS_TEMPLATES t ON t.ID = h.TEMPLATE_ID
    JOIN USER_ORDS_MODULES m ON m.ID = t.MODULE_ID
   WHERE m.NAME = 'Portal_medico' AND t.URI_TEMPLATE = 'Medico' AND h.METHOD = 'POST';
  v_nuevo := REGEXP_REPLACE(v_src, 'PR_SERVICIO_MED_EXAMEN1\s*\(', 'PR_SERVICIO_MED_EXAMEN1_V2(', 1, 0, 'i');
  v_nuevo := REGEXP_REPLACE(v_nuevo, 'PR_SERVICIO_MED_EXAMEN2\s*\(', 'PR_SERVICIO_MED_EXAMEN2_V2(', 1, 0, 'i');
  IF INSTR(UPPER(v_nuevo), 'PR_SERVICIO_MED_EXAMEN1_V2(') = 0 OR INSTR(UPPER(v_nuevo), 'PR_SERVICIO_MED_EXAMEN2_V2(') = 0 THEN
    RAISE_APPLICATION_ERROR(-20020, 'El handler vivo no llama a los procedimientos como se esperaba; no se creo Medico_v2.');
  END IF;
  ORDS.DEFINE_TEMPLATE(p_module_name => 'Portal_medico', p_pattern => 'Medico_v2',
                       p_comments => 'E-024: igual a Medico, llama a EXAMEN1/2_V2 (bitacora SERV_MED_LOG_PROC)');
  ORDS.DEFINE_HANDLER(p_module_name => 'Portal_medico', p_pattern => 'Medico_v2', p_method => 'POST',
                      p_source_type => ORDS.source_type_plsql, p_source => v_nuevo);
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('Servcio/Medico_v2 publicado (POST).');
END;
