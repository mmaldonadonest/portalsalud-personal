-- =============================================================================
-- BASE: PORTAL (JDBC, dentro de BIOMETRICO). Tablas nuevas del modulo de firmas digitalizadas
-- (paso 8 de docs/seguimiento-integracion-formatos-b.html, 20-oct-2026).
-- Requiere antes: docs/portal-aviso-privacidad-firma.sql (tabla SERV_MED_AVISO_PRIVACIDAD).
--
-- La IMAGEN de cada firma NO va aqui: va cifrada (AES-256-GCM) al almacen de archivos del portal
-- (disco + SERV_MED_FS_FILE con FILE_TYPE = 'firma_digitalizada'). Estas tablas guardan solo de
-- quien es, en que estado esta, que aviso acepto, quien elaboro cada documento y los folios.
-- Lo corre el usuario.
-- =============================================================================

-- 1) Firmas: una fila por firma registrada. Solo una VIGENTE por usuario (indice unico parcial).
--    ESTADO: PENDIENTE (cargada por un administrador, falta que el dueno acepte el aviso)
--            VIGENTE | SUSTITUIDA (el dueno registro otra) | REVOCADA (el dueno retiro su permiso)
--            DESACTIVADA (un administrador o la revision diaria: ya no es empleado activo)
--    Ninguna se borra: las anteriores sirven para verificar documentos ya emitidos.
CREATE TABLE SERV_MED_FIRMA (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO         VARCHAR2(100) NOT NULL,          -- usuario del portal = NSS del empleado
    NOMBRE          VARCHAR2(200),
    FILE_ID         NUMBER        NOT NULL,          -- SERV_MED_FS_FILE.ID del binario cifrado
    ORIGEN          VARCHAR2(20)  NOT NULL,          -- DIBUJO | IMAGEN | CARGA_ADMIN
    ESTADO          VARCHAR2(20)  NOT NULL,
    AVISO_VERSION   NUMBER,                          -- version del aviso que acepto el dueno
    ACEPTADO_AT     TIMESTAMP,
    ACEPTADO_IP     VARCHAR2(80),
    CREATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY      VARCHAR2(100) NOT NULL,
    UPDATED_AT      TIMESTAMP,
    UPDATED_BY      VARCHAR2(100),
    MOTIVO          VARCHAR2(400),
    CONSTRAINT CK_SERV_MED_FIRMA_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'VIGENTE', 'SUSTITUIDA', 'REVOCADA', 'DESACTIVADA')),
    CONSTRAINT CK_SERV_MED_FIRMA_ORIGEN CHECK (ORIGEN IN ('DIBUJO', 'IMAGEN', 'CARGA_ADMIN'))
);
CREATE INDEX IX_SERV_MED_FIRMA_USUARIO ON SERV_MED_FIRMA (USUARIO, ESTADO);
CREATE UNIQUE INDEX UQ_SERV_MED_FIRMA_VIGENTE ON SERV_MED_FIRMA (CASE WHEN ESTADO = 'VIGENTE' THEN USUARIO END);

-- 2) Autor de cada documento: quien lo elaboro y quien era el medico responsable, fijados al crearlo
--    (o en la primera impresion, para documentos anteriores). Al reimprimir se usan estos, no quien imprime.
--    REGISTRO: CONSULTA:<relacion> | ANTIDOPING:<id> | EXAMEN:<nss>:<fecha> | FTSO31:<nss>:<fecha>
CREATE TABLE SERV_MED_DOC_AUTOR (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REGISTRO        VARCHAR2(200) NOT NULL,
    NSS             VARCHAR2(20),
    ELABORO_USUARIO VARCHAR2(100),
    ELABORO_NOMBRE  VARCHAR2(200),
    MEDICO_USUARIO  VARCHAR2(100),
    MEDICO_NOMBRE   VARCHAR2(200),
    MEDICO_CEDULA   VARCHAR2(30),
    ORIGEN          VARCHAR2(20)  NOT NULL,          -- ALTA (al crear el documento) | PRIMERA_IMPRESION
    CREATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_SERV_MED_DOC_AUTOR UNIQUE (REGISTRO)
);

-- 3) Impresos con firma: folio + codigo de verificacion de cada impresion que llevo al menos una firma.
CREATE TABLE SERV_MED_FIRMA_IMPRESO (
    FOLIO              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO             VARCHAR2(12)  NOT NULL,
    FORMATO            VARCHAR2(20)  NOT NULL,
    REGISTRO           VARCHAR2(200) NOT NULL,
    NSS                VARCHAR2(20),
    FIRMA_MEDICO_ID    NUMBER,
    FIRMA_ELABORO_ID   NUMBER,
    ELABORO_NOMBRE     VARCHAR2(200),
    MEDICO_NOMBRE      VARCHAR2(200),
    MEDICO_CEDULA      VARCHAR2(30),
    IMPRESO_POR        VARCHAR2(100) NOT NULL,
    IMPRESO_AT         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_SERV_MED_FIRMA_IMP_CODIGO UNIQUE (CODIGO)
);
CREATE INDEX IX_SERV_MED_FIRMA_IMP_REG ON SERV_MED_FIRMA_IMPRESO (REGISTRO);

-- 4) Revision
SELECT TABLE_NAME FROM USER_TABLES
 WHERE TABLE_NAME IN ('SERV_MED_AVISO_PRIVACIDAD', 'SERV_MED_FIRMA', 'SERV_MED_DOC_AUTOR', 'SERV_MED_FIRMA_IMPRESO')
 ORDER BY 1;
