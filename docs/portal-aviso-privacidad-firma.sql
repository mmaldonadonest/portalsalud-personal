-- BASE: PORTAL (JDBC, dentro de BIOMETRICO). Tabla nueva SERV_MED_AVISO_PRIVACIDAD.
-- Aviso de privacidad que acepta cada persona antes de registrar su firma digitalizada
-- (modulo de firmas, paso 8 de docs/seguimiento-integracion-formatos-b.html, 20-oct-2026).
--
-- Decision del usuario 20-oct-2026: el aviso se actualiza SOLO por base de datos, sin pantalla
-- ni rol que lo modifique. Para cambiar el texto se INSERTA una version nueva (seccion 3);
-- nunca se hace UPDATE del texto de una version ya publicada: las aceptaciones guardan la
-- version que la persona leyo, y al publicar otra el portal vuelve a pedir la aceptacion.
--
-- La version 1 es un BORRADOR: DEBE SER REVISADA Y SUSTITUIDA por el area legal o RH antes
-- de usarse. Mientras la vigente tenga BORRADOR = 'S', el portal la muestra con la leyenda de
-- borrador.
-- Lo corre el usuario.
-- =============================================================================

-- 1) Tabla (una fila por version publicada)
CREATE TABLE SERV_MED_AVISO_PRIVACIDAD (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO           VARCHAR2(40)  NOT NULL,             -- FIRMA_DIGITALIZADA (otros avisos en el futuro)
    VERSION        NUMBER        NOT NULL,             -- 1, 2, 3... la mas alta del TIPO es la vigente
    TITULO         VARCHAR2(200) NOT NULL,
    TEXTO          CLOB          NOT NULL,
    BORRADOR       CHAR(1)       DEFAULT 'S' NOT NULL, -- 'S' = falta revision de legal o RH; 'N' = aprobado
    VIGENTE_DESDE  DATE          DEFAULT SYSDATE NOT NULL,
    CREATED_AT     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY     VARCHAR2(100) NOT NULL,
    CONSTRAINT UQ_SERV_MED_AVISO_VERSION UNIQUE (TIPO, VERSION),
    CONSTRAINT CK_SERV_MED_AVISO_BORRADOR CHECK (BORRADOR IN ('S', 'N'))
);

