-- [NOTA-1] CUENTA_NOMBRE (texto, no cuenta_id numerico) es la llave del mapeo a
--   proposito: es lo que YA fluye hoy por toda la app (EmpleadoDto.cuenta(), via
--   Catalogo/usuario -> bc.cuenta_nombre) - matchear por nombre (case-insensitive,
--   UPPER() en el indice) evita tener que agregar cuenta_id a ningun WS existente.
-- [NOTA-2] BLOQUE 4 asume que biometrico_cuenta_SAP tiene columnas cuenta_id y
--   cuenta_nombre (confirmado en el join de Catalogo/usuario: "bc.cuenta_nombre",
--   "c.cuenta_id=bc.cuenta_id") - no se corrio contra el diccionario de datos real
--   en esta sesion, verificar nombres exactos antes de aplicar.
-- [NOTA-3] Para resolver el predio-fino de un CASO (incapacidad/examen/etc.): del
--   lado Java, NSS -> Catalogo/usuario -> cuenta (nombre) -> buscar en el resultado
--   de cuenta_predio_lista (cacheado, no llamar por cada caso) -> predioId/nombre.
--   Si la cuenta no esta en el mapeo (predioNombre='0'), el caso cae en "Sin
--   asignar", nunca se descarta ni se rompe.
